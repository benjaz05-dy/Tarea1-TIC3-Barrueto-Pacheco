// Configuracion dinamica de acelerometro
static esp_err_t bmi270_configurar(
    int frecuencia,
    int rango
) {

    uint8_t odr;
    uint8_t codigo_rango;

    switch (frecuencia) {
        case 25:  odr = 0x06; break;
        case 50:  odr = 0x07; break;
        case 100: odr = 0x08; break;
        default:
            return ESP_ERR_INVALID_ARG;
    }

    switch (rango) {
        case 2:  codigo_rango = 0x00; break;
        case 4:  codigo_rango = 0x01; break;
        case 8:  codigo_rango = 0x02; break;
        case 16: codigo_rango = 0x03; break;
        default:
            return ESP_ERR_INVALID_ARG;
    }

    uint8_t registro_conf = 0x40;
    uint8_t registro_rango = 0x41;

    // Mantener configuracion de filtro y promedio
    // utilizada por el driver original
    uint8_t valor_conf = 0xA0 | odr;

    esp_err_t resultado = device_write(
        s_dev,
        &registro_conf,
        &valor_conf,
        1,
        TAG
    );

    if (resultado != ESP_OK) {
        return resultado;
    }

    resultado = device_write(
        s_dev,
        &registro_rango,
        &codigo_rango,
        1,
        TAG
    );

    if (resultado != ESP_OK) {
        return resultado;
    }

    // Actualizar factor de conversion
    s_rango_acc_actual = rango;

    vTaskDelay(pdMS_TO_TICKS(100));

    ESP_LOGI(
        TAG,
        "BMI270 configurado: %d Hz, +/- %d g",
        frecuencia,
        rango
    );

    return ESP_OK;
}


